import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { RECORDS } from "../src/catalog/index.js";
import { GAME_NAMES } from "../src/flat-schemas.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lines: string[] = [];
lines.push("/* Generated by scripts/generate-types.ts. Do not edit by hand. */");
lines.push("");
lines.push("export type VerificationTier = 0 | 1 | 2 | 3 | 4 | \"E\";");
lines.push("export type PrototypeLabel =");
lines.push("  | \"PROTOTYPE-UNVERIFIED\"");
lines.push("  | \"SEEDED-OPEN-DATA\"");
lines.push("  | \"COMMUNITY-REPORTED\"");
lines.push("  | \"VERIFIED\";");
lines.push("");
lines.push("export interface FieldEvidence {");
lines.push("  protocol_version: string;");
lines.push("  verifier_role: \"trained_verifier\" | \"peer\" | \"operator\" | \"importer\" | \"desk_reviewer\";");
lines.push("  method: string;");
lines.push("  observed_at: string;");
lines.push("  photo_ids?: string[];");
lines.push("}");
lines.push("");
lines.push("export type FieldValue =");
lines.push("  | string");
lines.push("  | number");
lines.push("  | boolean");
lines.push("  | string[]");
lines.push("  | number[][]");
lines.push("  | \"unknown\"");
lines.push("  | \"UNKNOWN\";");
lines.push("");
lines.push("export interface FieldFact {");
lines.push("  value: FieldValue;");
lines.push("  unit?: \"mm\" | \"m\" | \"kg\" | \"percent\" | \"degrees\" | \"ratio\" | null;");
lines.push("  method?: string | null;");
lines.push("  observed_at?: string;");
lines.push("  source_id: string;");
lines.push("  licence: string;");
lines.push("  retrieved_at: string;");
lines.push("  tier: VerificationTier;");
lines.push("  source_name?: string;");
lines.push("  source_key?: string;");
lines.push("  raw?: string | number | null;");
lines.push("  derived?: boolean;");
lines.push("  tri_state_observation?: boolean;");
lines.push("  evidence?: FieldEvidence;");
lines.push("}");
lines.push("");
lines.push("export interface Provenance {");
lines.push("  tier: VerificationTier;");
lines.push("  prototype_label?: PrototypeLabel;");
lines.push("  source_name: string;");
lines.push("  source_id: string;");
lines.push("  source_date: string;");
lines.push("  record_date: string;");
lines.push("  licence_id: string;");
lines.push("  retrieved_at: string;");
lines.push("  evidence?: FieldEvidence;");
lines.push("}");
lines.push("");
lines.push("export interface CanonicalRecord {");
lines.push("  record_type: string;");
lines.push("  schema_version: string;");
lines.push("  id: string;");
lines.push("  record_status: \"draft\" | \"in_review\" | \"published\" | \"stale_flagged\" | \"archived\" | \"disputed\";");
lines.push("  publication_context: \"canonical\" | \"prototype\";");
lines.push("  example?: boolean;");
lines.push("  provenance: Provenance;");
lines.push("  facts?: Record<string, FieldFact>;");
lines.push("  imported_facts?: Record<string, FieldFact>;");
lines.push("}");
lines.push("");

function typeName(recordType: string): string {
  return recordType
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("") + "Facts";
}

for (const record of RECORDS) {
  const facts = record.fields.filter((field) => field.placement === "facts");
  lines.push(`export interface ${typeName(record.recordType)} {`);
  for (const field of facts) {
    lines.push(`  /** ${field.description.replaceAll("*/", "")} */`);
    const optional = field.requirement === "required" ? "" : "?";
    lines.push(`  ${field.property}${optional}: FieldFact;`);
  }
  lines.push("}");
  lines.push("");
}

lines.push("export type GameName =");
for (const name of GAME_NAMES) lines.push(`  | "${name}"`);
lines.push(";");
lines.push("");
lines.push("export interface ImportFieldValue {");
lines.push("  value: string | number | number[][];");
lines.push("  source_id: string;");
lines.push("  licence: string;");
lines.push("  retrieved_at: string;");
lines.push("  tier: 0 | 1 | 2 | 3 | 4;");
lines.push("  source_key?: string;");
lines.push("  raw?: string | number | null;");
lines.push("  derived?: boolean;");
lines.push("}");
lines.push("");
lines.push("export interface ImportRecord {");
lines.push("  id: string;");
lines.push("  tranche: \"venue\" | \"washroom\" | \"path\" | \"transit\";");
lines.push("  region: string;");
lines.push("  fields: Record<string, ImportFieldValue>;");
lines.push("}");
lines.push("");

const out = path.join(root, "src/generated/types.ts");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`wrote ${lines.length} lines of types`);
