import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const source=readFileSync(new globalThis.URL("./p20ah-browser-form.ts",import.meta.url),"utf8");
test("P20AH browser reader exports form observation",()=>assert.match(source,/export async function observeForm/));
test("P20AH browser reader exports focus handoff helper",()=>assert.match(source,/export async function focusFirstInvalid/));
test("P20AH browser reader exports submit observer",()=>assert.match(source,/export async function submitAndObserve/));
test("P20AH browser reader observes form element by id",()=>assert.match(source,/getElementById\(id\)/));
test("P20AH browser reader checks HTMLFormElement",()=>assert.match(source,/instanceof HTMLFormElement/));
test("P20AH browser reader records visible label text",()=>assert.match(source,/labelText:/));
test("P20AH browser reader records accessible name",()=>assert.match(source,/accessibleName:/));
test("P20AH browser reader records aria-invalid",()=>assert.match(source,/aria-invalid/));
test("P20AH browser reader records described-by references",()=>assert.match(source,/aria-describedby/));
test("P20AH browser reader records error live region",()=>assert.match(source,/errorLive/));
test("P20AH browser reader records focus ownership",()=>assert.match(source,/document\.activeElement/));
test("P20AH browser reader records viewport target size",()=>assert.match(source,/width:rect\.width,height:rect\.height/));
test("P20AH browser reader observes group legend",()=>assert.match(source,/querySelector\("legend"\)/));
test("P20AH browser reader records selected option count",()=>assert.match(source,/selectedCount/));
test("P20AH browser reader has a bounded form id",()=>assert.match(source,/Form id is invalid/));
test("P20AH browser reader does not write storage",()=>assert.doesNotMatch(source,/localStorage|sessionStorage|indexedDB/));
test("P20AH browser reader does not send requests",()=>assert.doesNotMatch(source,/sendBeacon|fetch\s*\(|XMLHttpRequest/));
test("P20AH browser reader does not set field values",()=>assert.doesNotMatch(source,/\.value\s*=/));
test("P20AH focus helper locates aria-invalid fields",()=>assert.match(source,/aria-invalid="true"/));
test("P20AH focus helper observes before and after focus",()=>assert.match(source,/before,after,target/));
