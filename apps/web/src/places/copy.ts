export function say(locale: Locale, key: CopyKey, values: Record<string, string | number> = {}): string {
  const template = locale === "fr" ? FR[key] : EN[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

/** A distance in plain words: metres under 1 km, else kilometres with one decimal. */
export function distanceWords(locale: Locale, metres: number): string {
  if (metres < 1000) return say(locale, "metres", { n: Math.max(10, Math.round(metres / 10) * 10) });
  const km = (Math.round(metres / 100) / 10).toFixed(1);
  return say(locale, "kilometres", { n: locale === "fr" ? km.replace(".", ",") : km });
}
