export function coordinationQuestion(topic: BriefTopic, language: Language): string {
  return COORDINATION_QUESTIONS[topic][language === "fr" ? 1 : 0];
}
export function auditCoordinationCopy(): readonly string[] {
  const issues: string[] = [];
  const en = COORDINATION_COPY.en;
  const fr = COORDINATION_COPY.fr;
  for (const key of Object.keys(en) as Array<keyof typeof en>) {
    if (en[key].trim().length === 0 || fr[key].trim().length === 0) issues.push(key);
  }
  for (const [name, record] of Object.entries({ topics: COORDINATION_TOPICS, priorities: COORDINATION_PRIORITIES,
    statuses: COORDINATION_STATUSES, filters: COORDINATION_FILTERS, sorts: COORDINATION_SORTS })) {
    if (Object.keys(record.en).sort().join() !== Object.keys(record.fr).sort().join()) issues.push(name);
  }
  return issues;
}
