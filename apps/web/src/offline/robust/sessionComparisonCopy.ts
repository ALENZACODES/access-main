export function comparisonSummary(comparison: SnapshotComparison, language: Language): string {
  const c = SESSION_COPY[language];
  const colon = language === "fr" ? "\u00a0:" : ":";
  return [
    `${c.added}${colon} ${comparison.newlySaved}`,
    `${c.lost}${colon} ${comparison.noLongerSaved}`,
    `${c.unknownCount}${colon} ${comparison.unknown}`,
    `${c.uncertainCount}${colon} ${comparison.cannotCompare}`,
  ].join(". ") + ".";
}
