export function workbookSummaryText(value: WorkbookSummary, language: Language): string {
  const c = WORKBOOK_COPY[language];
  const separator = language === "fr" ? "\u00a0: " : ": ";
  const part = (label: string, count: number | null): string =>
    `${label}${separator}${count === null ? "UNKNOWN" : count.toLocaleString(language === "fr" ? "fr-CA" : "en-CA")}`;
  return [part(c.total, value.listed), part(c.beforeSaved, value.beforeSaved),
    part(c.afterSaved, value.afterSaved), part(c.changed, value.changed),
    part(c.unknownCount, value.unknown), part(c.openNotes, value.openNotes)].join(". ");
}
