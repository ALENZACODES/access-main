import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fictionalManifest, UNKNOWN } from './document-outline-contract.mjs';
import { reviewManifest } from './document-outline-review.mjs';
import { compareManifest } from './document-outline-delta.mjs';
import {
  WORDS, escapeHtml, guardCsv, frenchPunctuation,
  reportJson, reportCsv, reportText, reportHtml, renderReport,
} from './document-outline-report.mjs';
const fixture = () => fictionalManifest();
const rev = () => reviewManifest(fixture());
const diff = () => compareManifest(fixture(),fixture());
const render = (format = 'html', language = 'en', before = null) => renderReport(fixture(),{format,language,before});
test('English labels are present', () => assert.ok(WORDS.en.title));
test('French labels are present', () => assert.ok(WORDS.fr.title));
test('English and French report titles differ', () => assert.notEqual(WORDS.en.title,WORDS.fr.title));
test('French caution keeps exact UNKNOWN', () => assert.ok(WORDS.fr.caution.includes(UNKNOWN)));
test('English caution keeps exact UNKNOWN', () => assert.ok(WORDS.en.caution.includes(UNKNOWN)));
test('French output avoids a localized replacement for UNKNOWN', () => assert.ok(!/\bInconnu\b/iu.test(WORDS.fr.caution)));
test('HTML escaping protects & before other characters', () => assert.equal(escapeHtml('&'), '&amp;'));
test('HTML escaping protects opening angle bracket', () => assert.equal(escapeHtml('<'), '&lt;'));
test('HTML escaping protects closing angle bracket', () => assert.equal(escapeHtml('>'), '&gt;'));
test('HTML escaping protects double quotes', () => assert.equal(escapeHtml('"'), '&quot;'));
test('HTML escaping protects apostrophe', () => assert.equal(escapeHtml("'"), '&#39;'));
test('HTML escaping handles a combined malicious payload', () => assert.equal(escapeHtml('<script>alert("x")</script>'), '&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt;'));
test('HTML escaping handles null', () => assert.equal(escapeHtml(null),''));
test('HTML escaping handles undefined', () => assert.equal(escapeHtml(undefined),''));
test('HTML escaping retains plain words', () => assert.equal(escapeHtml('Hello'),'Hello'));
test('HTML escaping protects URLs with query ampersand', () => assert.equal(escapeHtml('a?x=1&y=2'),'a?x=1&amp;y=2'));
test('CSV always surrounds safe text in quotes', () => assert.equal(guardCsv('help'),'"help"'));
test('CSV doubles embedded quotes', () => assert.equal(guardCsv('a"b'),'"a""b"'));
test('CSV escapes leading equals formula', () => assert.equal(guardCsv('=SUM(A1:A2)'),"\"'=SUM(A1:A2)\""));
test('CSV escapes leading plus formula', () => assert.equal(guardCsv('+2+2'),"\"'+2+2\""));
test('CSV escapes leading negative expression', () => assert.equal(guardCsv('-cmd'),"\"'-cmd\""));
test('CSV escapes leading at-sign', () => assert.equal(guardCsv('@SUM(A1)'),"\"'@SUM(A1)\""));
test('CSV escapes leading tab and formula', () => assert.equal(guardCsv('\t=2'),"\"'\t=2\""));
test('CSV escapes leading spaces and formula', () => assert.equal(guardCsv('  =2'),"\"'  =2\""));
test('CSV does not prepend apostrophe to ordinary word', () => assert.equal(guardCsv('Notes'),'"Notes"'));
test('CSV preserves commas inside field quotes', () => assert.equal(guardCsv('a,b'),'"a,b"'));
test('CSV preserves newlines within quoted field', () => assert.equal(guardCsv('a\nb'),'"a\nb"'));
test('CSV translates null to exact UNKNOWN', () => assert.equal(guardCsv(null),'"UNKNOWN"'));
test('French punctuation inserts NBSP before colon', () => assert.equal(frenchPunctuation('Titre: exemple','fr'),'Titre\u00a0: exemple'));
test('French punctuation inserts narrow NBSP before semicolon', () => assert.equal(frenchPunctuation('Un; deux','fr'),'Un\u202f; deux'));
test('French punctuation inserts narrow NBSP before exclamation', () => assert.equal(frenchPunctuation('Bravo!','fr'),'Bravo\u202f!'));
test('French punctuation inserts narrow NBSP before question', () => assert.equal(frenchPunctuation('Pourquoi?','fr'),'Pourquoi\u202f?'));
test('French punctuation inserts narrow NBSP after opening guillemet', () => assert.equal(frenchPunctuation('«mot','fr'),'«\u202fmot'));
test('French punctuation inserts narrow NBSP before closing guillemet', () => assert.equal(frenchPunctuation('mot»','fr'),'mot\u202f»'));
test('English punctuation is unchanged', () => assert.equal(frenchPunctuation('Title: example!','en'),'Title: example!'));
test('French conversion leaves UNKNOWN unchanged', () => assert.equal(frenchPunctuation(UNKNOWN,'fr'),UNKNOWN));
test('French spacing normalization is deterministic', () => assert.equal(frenchPunctuation('A: B','fr'),frenchPunctuation('A: B','fr')));
test('JSON export parses as valid JSON', () => assert.doesNotThrow(()=>JSON.parse(reportJson(rev()))));
test('JSON export has schema version 1', () => assert.equal(JSON.parse(reportJson(rev())).schemaVersion,1));
test('JSON export has a report object', () => assert.equal(typeof JSON.parse(reportJson(rev())).report,'object'));
test('JSON export has no comparison without before', () => assert.equal(JSON.parse(reportJson(rev())).comparison,null));
test('JSON export includes comparison with before', () => assert.ok(JSON.parse(reportJson(rev(),diff())).comparison));
test('JSON export ends in newline', () => assert.ok(reportJson(rev()).endsWith('\n')));
test('JSON export preserves explicit source field', () => assert.ok(JSON.parse(reportJson(rev())).report.documents[0].source));
test('JSON export preserves exact UNKNOWN evidence tier', () => assert.ok(JSON.parse(reportJson(rev())).report.documents.some(d=>d.tier===UNKNOWN)));
test('CSV export begins with headings', () => assert.ok(reportCsv(rev()).startsWith('"Path"')));
test('French CSV export begins with French heading', () => assert.ok(reportCsv(rev(),'fr').startsWith('"Chemin"')));
test('CSV report contains CRLF record separator', () => assert.ok(reportCsv(rev()).includes('\r\n')));
test('CSV report includes issue reason', () => assert.ok(reportCsv(rev()).includes('"DOCUMENT_UNREVIEWED"')));
test('CSV report appends comparison section', () => assert.ok(reportCsv(rev(),'en',diff()).includes('"Document changes"')));
test('CSV report does not include HTML element markup', () => assert.ok(!reportCsv(rev()).includes('<table')));
test('text report starts with English title', () => assert.ok(reportText(rev()).startsWith(WORDS.en.title)));
test('text report starts with French title', () => assert.ok(reportText(rev(),'fr').startsWith(WORDS.fr.title)));
test('text report includes explicit UNKNOWN', () => assert.ok(reportText(rev()).includes(UNKNOWN)));
test('text report includes report date', () => assert.ok(reportText(rev()).includes('2026-11-21')));
test('text report includes issue source path', () => assert.ok(reportText(rev()).includes('help/introduction.en.md')));
test('text report includes comparison heading', () => assert.ok(reportText(rev(),'en',diff()).includes(WORDS.en.delta)));
test('text report does not include HTML head', () => assert.ok(!reportText(rev()).includes('<head')));
test('text report ends with newline', () => assert.ok(reportText(rev()).endsWith('\n')));
test('HTML report has valid doctype', () => assert.match(reportHtml(rev()),/^<!doctype html>/u));
test('English HTML has en language tag', () => assert.ok(reportHtml(rev()).includes('<html lang="en">')));
test('French HTML has fr language tag', () => assert.ok(reportHtml(rev(),'fr').includes('<html lang="fr">')));
test('HTML report has page title', () => assert.ok(reportHtml(rev()).includes('<title>')));
test('HTML report contains main landmark', () => assert.ok(reportHtml(rev()).includes('<main id="main">')));
test('HTML report has skip navigation link', () => assert.ok(reportHtml(rev()).includes('href="#main"')));
test('HTML report has one H1', () => assert.equal((reportHtml(rev()).match(/<h1>/gu)??[]).length,1));
test('HTML report has viewport metadata', () => assert.ok(reportHtml(rev()).includes('name="viewport"')));
test('HTML report has visible keyboard focus rule', () => assert.ok(reportHtml(rev()).includes(':focus-visible')));
test('HTML report has reduced-motion consideration', () => assert.ok(reportHtml(rev()).includes('prefers-reduced-motion')));
test('HTML report identifies row headings', () => assert.ok(reportHtml(rev()).includes('scope="col"')));
test('HTML report keeps issues inside a named section', () => assert.ok(reportHtml(rev()).includes('aria-labelledby="findings"')));
test('HTML report contains inventory table', () => assert.ok(reportHtml(rev()).includes('id="documents"')));
test('HTML report contains manual-review table', () => assert.ok(reportHtml(rev()).includes('id="reviews"')));
test('HTML report includes delta section when supplied', () => assert.ok(reportHtml(rev(),'en',diff()).includes('id="delta"')));
test('HTML report omits delta section when not supplied', () => assert.ok(!reportHtml(rev()).includes('id="delta"')));
test('HTML report includes exact UNKNOWN warning', () => assert.ok(reportHtml(rev()).includes(UNKNOWN)));
test('HTML report does not load remote resources', () => assert.ok(!/<script|<link href=/u.test(reportHtml(rev()))));
test('HTML report does not include form submission controls', () => assert.ok(!/<form\b/u.test(reportHtml(rev()))));
test('HTML report preserves French apostrophe glyph', () => assert.ok(reportHtml(rev(),'fr').includes('d’examen')));
test('HTML output is deterministic', () => assert.equal(reportHtml(rev()),reportHtml(rev())));
test('render supports html', () => assert.equal(render('html').mime,'text/html'));
test('render supports json', () => assert.equal(render('json').mime,'application/json'));
test('render supports csv', () => assert.equal(render('csv').mime,'text/csv'));
test('render supports text', () => assert.equal(render('text').mime,'text/plain'));
test('render supports French text', () => assert.equal(render('text','fr').ok,true));
test('render supports French HTML', () => assert.equal(render('html','fr').ok,true));
test('render rejects unsupported language', () => assert.equal(render('html','es').ok,false));
test('render rejects unsupported format', () => assert.equal(render('pdf').ok,false));
test('render rejects invalid manifest', () => assert.equal(renderReport({}).ok,false));
test('render rejects invalid previous snapshot', () => assert.equal(render('json','en',{}).ok,false));
test('render returns a review object', () => assert.equal(render('html').review.ok,true));
test('render returns delta when before supplied', () => assert.equal(render('json','en',fixture()).delta.ok,true));
test('render leaves comparison null if not supplied', () => assert.equal(render('json').delta,null));
test('render reports source tier without inventing evidence', () => assert.ok(render('json').content.includes(UNKNOWN)));
test('render does not mutate the manifest', () => {const m=fixture(),s=JSON.stringify(m);renderReport(m);assert.equal(JSON.stringify(m),s);});
test('render is deterministic with explicit review date', () => assert.equal(render('html').content,render('html').content));
for (const lang of ['en','fr']) for (const format of ['html','csv','json','text']) {
  test(`all combinations render ${lang}/${format}`, () => assert.equal(render(format,lang).ok,true));
}
