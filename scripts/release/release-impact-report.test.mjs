import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  LABELS, escapeHtml, csvCell, localPunctuation, reportData, summaryRows,
  reportText, reportCsv, reportHtml, reportJson, renderReport,
} from './release-impact-report.mjs';
import { asset, manifest, bilingual, DAY, SHA_B } from './release-impact-fixtures.mjs';
import { UNKNOWN } from './release-impact-contract.mjs';
const ready = () => reportData(bilingual(), { today: DAY }).value;
const output = (format = 'html', language = 'en', after = bilingual(), before = null) => renderReport(after, { format, language, before, today: DAY });
test('both languages have report titles', () => assert.ok(LABELS.en.title && LABELS.fr.title));
test('French title differs from English title', () => assert.notEqual(LABELS.en.title, LABELS.fr.title));
test('both languages retain UNKNOWN token', () => assert.equal(LABELS.en.unknown, LABELS.fr.unknown));
test('French caution contains UNKNOWN', () => assert.match(LABELS.fr.caution, /UNKNOWN/u));
test('English caution contains UNKNOWN', () => assert.match(LABELS.en.caution, /UNKNOWN/u));
test('English caution does not certify accessibility', () => assert.match(LABELS.en.caution, /not an accessibility inspection/u));
test('French caution does not certify accessibility', () => assert.match(LABELS.fr.caution, /ne constitue pas une inspection/u));
test('HTML escaping replaces ampersands', () => assert.equal(escapeHtml('&'), '&amp;'));
test('HTML escaping replaces opening angle', () => assert.equal(escapeHtml('<'), '&lt;'));
test('HTML escaping replaces closing angle', () => assert.equal(escapeHtml('>'), '&gt;'));
test('HTML escaping replaces quotes', () => assert.equal(escapeHtml('"'), '&quot;'));
test('HTML escaping replaces apostrophe', () => assert.equal(escapeHtml("'"), '&#39;'));
test('HTML escaping handles null', () => assert.equal(escapeHtml(null), ''));
test('HTML escaping handles undefined', () => assert.equal(escapeHtml(undefined), ''));
test('HTML escaping preserves safe letters', () => assert.equal(escapeHtml('A B'), 'A B'));
test('HTML escaping does not double-escape raw safe text', () => assert.equal(escapeHtml('no issues'), 'no issues'));
test('HTML escaping protects combined markup payload', () => assert.equal(escapeHtml('<img src="x">'), '&lt;img src=&quot;x&quot;&gt;'));
test('CSV values enclosed in double quotes', () => assert.equal(csvCell('safe'), '"safe"'));
test('CSV embedded quotes doubled', () => assert.equal(csvCell('a"b'), '"a""b"'));
test('CSV leading equals sign escaped', () => assert.equal(csvCell('=SUM(1,2)'), '"\'=SUM(1,2)"'));
test('CSV leading plus sign escaped', () => assert.equal(csvCell('+1'), '"\'+1"'));
test('CSV leading minus sign escaped', () => assert.equal(csvCell('-cmd'), '"\'-cmd"'));
test('CSV leading at sign escaped', () => assert.equal(csvCell('@import'), '"\'@import"'));
test('CSV leading tab before formula escaped', () => assert.equal(csvCell('\t=SUM(1,2)'), '"\'\t=SUM(1,2)"'));
test('CSV leading carriage return before formula escaped', () => assert.equal(csvCell('\r=1'), '"\'\r=1"'));
test('CSV ordinary commas remain safely quoted', () => assert.equal(csvCell('a,b'), '"a,b"'));
test('CSV unknown value is UNKNOWN', () => assert.equal(csvCell(null), '"UNKNOWN"'));
test('CSV value zero retained', () => assert.equal(csvCell(0), '"0"'));
test('CSV status token retained', () => assert.equal(csvCell(UNKNOWN), '"UNKNOWN"'));
test('French colon uses NBSP', () => assert.equal(localPunctuation('Source: x', 'fr'), 'Source\u00a0: x'));
test('French semicolon uses narrow NBSP', () => assert.equal(localPunctuation('x; y', 'fr'), 'x\u202f; y'));
test('French question mark uses narrow NBSP', () => assert.equal(localPunctuation('Pourquoi?', 'fr'), 'Pourquoi\u202f?'));
test('French exclamation uses narrow NBSP', () => assert.equal(localPunctuation('Attention!', 'fr'), 'Attention\u202f!'));
test('French guillemets have inside narrow spaces', () => assert.equal(localPunctuation('«bonjour»', 'fr'), '«\u202fbonjour\u202f»'));
test('English punctuation is unchanged', () => assert.equal(localPunctuation('x; y?', 'en'), 'x; y?'));
test('French punctuation is idempotent around colon', () => assert.equal(localPunctuation(localPunctuation('Source: x', 'fr'), 'fr'), 'Source\u00a0: x'));
test('French punctuation is idempotent around semicolon', () => assert.equal(localPunctuation(localPunctuation('x; y', 'fr'), 'fr'), 'x\u202f; y'));
test('bilingual reportData passes', () => assert.equal(reportData(bilingual(), { today: DAY }).ok, true));
test('invalid manifest fails before rendering', () => assert.equal(reportData({}).ok, false));
test('invalid previous manifest fails before rendering', () => assert.equal(reportData(bilingual(), { before: { version: 9 }, today: DAY }).ok, false));
test('reportData does not include comparison without before', () => assert.equal(ready().comparison, null));
test('reportData includes comparison when previous supplied', () => assert.notEqual(reportData(bilingual(), { before: bilingual(), today: DAY }).value.comparison, null));
test('reportData retains manifest asset count', () => assert.equal(ready().manifest.assets.length, 3));
test('reportData retains manual task array', () => assert.ok(Array.isArray(ready().tasks)));
test('summaryRows names number of assets', () => assert.deepEqual(summaryRows(ready()).find(x => x[0] === 'assets'), ['assets', 3]));
test('summaryRows names number of roots', () => assert.deepEqual(summaryRows(ready()).find(x => x[0] === 'roots'), ['roots', 2]));
test('summaryRows names total bytes', () => assert.deepEqual(summaryRows(ready()).find(x => x[0] === 'totalBytes'), ['totalBytes', 300]));
test('summaryRows includes orphan count', () => assert.ok(summaryRows(ready()).some(x => x[0] === 'orphans')));
test('summaryRows includes review count', () => assert.ok(summaryRows(ready()).some(x => x[0] === 'review')));
test('English text shows title', () => assert.match(reportText(ready(), 'en', DAY), /Release dependency impact ledger/u));
test('French text shows localized title', () => assert.match(reportText(ready(), 'fr', DAY), /Registre des impacts/u));
test('English text includes source attribution', () => assert.match(reportText(ready(), 'en', DAY), /Fictional build manifest/u));
test('French text retains licence label', () => assert.match(reportText(ready(), 'fr', DAY), /Licence/u));
test('text includes original retrieved date', () => assert.match(reportText(ready(), 'en', DAY), /2026-11-21/u));
test('text includes manifest entry', () => assert.match(reportText(ready(), 'en', DAY), /assets\/en\.js/u));
test('text emits no invented place facts', () => assert.doesNotMatch(reportText(ready(), 'en', DAY), /certified accessible/iu));
test('text with no dependencies shows UNKNOWN', () => assert.match(reportText(ready(), 'en', DAY), /Dependencies: UNKNOWN/u));
test('text with comparison has before and after section', () => {
  const data = reportData(bilingual(), { before: bilingual(), today: DAY }).value;
  assert.match(reportText(data, 'en', DAY), /Before and after comparison/u);
});
test('text with changed asset describes change', () => {
  const old = bilingual(), next = bilingual(); next.assets[0].sha256 = SHA_B;
  assert.match(reportText(reportData(next, { before: old, today: DAY }).value, 'en', DAY), /changed/u);
});
test('CSV starts UTF-8 BOM', () => assert.ok(reportCsv(ready()).startsWith('\uFEFF')));
test('CSV is terminated with CRLF', () => assert.ok(reportCsv(ready()).endsWith('\r\n')));
test('CSV includes header and three asset rows', () => assert.equal(reportCsv(ready()).split('\r\n').filter(Boolean).length, 4));
test('CSV contains SHA-256 header', () => assert.match(reportCsv(ready()), /SHA-256/u));
test('CSV retains bilingual locale values', () => assert.match(reportCsv(ready()), /"fr"/u));
test('CSV preserves tier without translation', () => assert.match(reportCsv(ready(), 'fr'), /source-documented/u));
test('CSV escapes formula-like malicious source', () => {
  const data = manifest(asset('root', { source: '=SUM(1,2)', entry: true, locale: 'both' }));
  assert.match(reportCsv(reportData(data).value), /"'=SUM\(1,2\)"/u);
});
test('CSV escapes double quote within source', () => {
  const data = manifest(asset('root', { source: 'A "fictional" source', entry: true, locale: 'both' }));
  assert.match(reportCsv(reportData(data).value), /A ""fictional"" source/u);
});
test('HTML document has doctype', () => assert.match(reportHtml(ready()), /^<!doctype html>/u));
test('HTML English document declares language', () => assert.match(reportHtml(ready(), 'en'), /<html lang="en">/u));
test('HTML French document declares language', () => assert.match(reportHtml(ready(), 'fr'), /<html lang="fr">/u));
test('HTML has one main landmark', () => assert.equal((reportHtml(ready()).match(/<main>/gu) ?? []).length, 1));
test('HTML contains H1', () => assert.match(reportHtml(ready()), /<h1>/u));
test('HTML contains H2 for inventory', () => assert.match(reportHtml(ready()), /<h2 id="records">/u));
test('HTML contains H2 for review', () => assert.match(reportHtml(ready()), /<h2 id="review">/u));
test('HTML table has row headers', () => assert.match(reportHtml(ready()), /scope="row"/u));
test('HTML table has column headers', () => assert.match(reportHtml(ready()), /scope="col"/u));
test('HTML provides visible keyboard focus', () => assert.match(reportHtml(ready()), /:focus-visible/u));
test('HTML nav links have minimum target size', () => assert.match(reportHtml(ready()), /min-height:44px;min-width:44px/u));
test('HTML has no remote JS', () => assert.doesNotMatch(reportHtml(ready()), /<script/u));
test('HTML has no remote CSS', () => assert.doesNotMatch(reportHtml(ready()), /<link[^>]+stylesheet/u));
test('HTML has no interactive handler', () => assert.doesNotMatch(reportHtml(ready()), /onclick=/u));
test('HTML includes explicit caution', () => assert.match(reportHtml(ready()), /manifest is not an accessibility inspection/u));
test('French HTML includes caution', () => assert.match(reportHtml(ready(), 'fr'), /UNKNOWN reste UNKNOWN/u));
test('French HTML report date uses NBSP before colon', () => assert.match(reportHtml(ready(), 'fr', DAY), /Date du rapport\u00a0: 2026-11-21/u));
test('HTML escapes malicious source markup', () => {
  const data = manifest(asset('root', { entry: true, locale: 'both', source: '<b>fictional</b>' }));
  assert.match(reportHtml(reportData(data).value), /&lt;b&gt;fictional&lt;\/b&gt;/u);
});
test('HTML contains no unescaped malicious source markup', () => {
  const data = manifest(asset('root', { entry: true, locale: 'both', source: '<script>bad</script>' }));
  assert.doesNotMatch(reportHtml(reportData(data).value), /<script>bad/u);
});
test('HTML includes changes only when comparison requested', () => assert.doesNotMatch(reportHtml(ready()), /id="changes"/u));
test('HTML includes changes when comparison requested', () => {
  const data = reportData(bilingual(), { before: bilingual(), today: DAY }).value;
  assert.match(reportHtml(data), /id="changes"/u);
});
test('JSON report parses successfully', () => assert.equal(JSON.parse(reportJson(ready())).schemaVersion, 1));
test('JSON report keeps source references', () => assert.equal(JSON.parse(reportJson(ready())).manifest.assets[0].source, 'Fictional build manifest'));
test('JSON report includes graph findings', () => assert.equal(JSON.parse(reportJson(ready())).graph.roots.length, 2));
test('JSON report includes explicit manual tasks', () => assert.ok(Array.isArray(JSON.parse(reportJson(ready())).tasks)));
test('JSON report includes caution', () => assert.match(JSON.parse(reportJson(ready())).warning, /UNKNOWN/u));
test('renderReport defaults to HTML', () => assert.equal(output().value.format, 'html'));
test('renderReport French option works', () => assert.equal(output('text', 'fr').value.language, 'fr'));
test('renderReport JSON option works', () => assert.equal(output('json').ok, true));
test('renderReport CSV option works', () => assert.equal(output('csv').ok, true));
test('renderReport text option works', () => assert.equal(output('text').ok, true));
test('renderReport invalid format rejected', () => assert.equal(output('exe').ok, false));
test('renderReport invalid language rejected', () => assert.equal(output('html', 'es').ok, false));
test('renderReport invalid input rejected', () => assert.equal(output('html', 'en', {}).ok, false));
test('renderReport file ends in html', () => assert.ok(output('html').value.suggestedFile.endsWith('.html')));
test('renderReport text file ends in txt', () => assert.ok(output('text').value.suggestedFile.endsWith('.txt')));
test('renderReport includes date in suggested filename', () => assert.ok(output('json').value.suggestedFile.includes(DAY)));
test('renderReport repeated calls produce identical output', () => assert.equal(output().value.content, output().value.content));
test('renderReport does not mutate fictional fixtures', () => {
  const after = bilingual(), prior = JSON.stringify(after);
  output('json', 'en', after);
  assert.equal(JSON.stringify(after), prior);
});
